#!/usr/bin/env python3
"""Generate ready-to-install styles; no build is required by end users.
Reference declarations stay unchanged. Only page theme selectors become :host.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def build_css():
    reference = (ROOT / 'vendor/reborn14/styles-chatgpt.reference.css').read_text(encoding='utf-8')
    reference = reference.replace(':root {', ':host {').replace(
        'html.dark, body.dark, html[data-theme="dark"], [data-theme="dark"], [data-color-mode="dark"] {',
        ':host([data-theme="dark"]) {').replace('html.dark .', ':host([data-theme="dark"]) .')
    return '\n'.join((
        (ROOT / 'src/shell.css').read_text(encoding='utf-8'), reference,
        (ROOT / 'src/theme.css').read_text(encoding='utf-8'),
        (ROOT / 'src/extras.css').read_text(encoding='utf-8')))
if __name__ == '__main__':
    css = build_css()
    # Byte writes keep the embedded and standalone styles identical on Windows.
    (ROOT / 'src/timeline.css').write_bytes(css.encode('utf-8'))
    script = '// Generated by tools/sync_styles.py; includes MIT-licensed Reborn14 styles.\n' + \
        'globalThis.GTNextCSS = ' + json.dumps(css, ensure_ascii=False) + ';\n'
    (ROOT / 'src/styles.js').write_bytes(script.encode('utf-8'))
    print('Updated src/timeline.css and src/styles.js')
