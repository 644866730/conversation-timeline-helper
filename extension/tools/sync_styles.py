#!/usr/bin/env python3
"""Generate ready-to-install styles; no build is required by end users.
Reference declarations stay unchanged. Only page theme selectors become :host.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def build_css():
    reference = (ROOT / 'vendor/reborn14/styles-chatgpt.reference.css').read_text(encoding='utf-8')
    reference = reference.replace(':root {', ':host {').replace(
        'html.dark, body.dark, html[data-theme="dark"], [data-theme="dark"], [data-color-mode="dark"] {',
        ':host([data-theme="dark"]) {').replace('html.dark .', ':host([data-theme="dark"]) .')
    return (ROOT / 'src/shell.css').read_text(encoding='utf-8') + '\n' + reference + '\n' + (ROOT / 'src/extras.css').read_text(encoding='utf-8')
if __name__ == '__main__':
    css = build_css()
    (ROOT / 'src/timeline.css').write_text(css, encoding='utf-8')
    (ROOT / 'src/styles.js').write_text('// Generated by tools/sync_styles.py; includes MIT-licensed Reborn14 styles.\n' +
        'globalThis.GTNextCSS = ' + json.dumps(css, ensure_ascii=False) + ';\n', encoding='utf-8')
    print('Updated src/timeline.css and src/styles.js')
